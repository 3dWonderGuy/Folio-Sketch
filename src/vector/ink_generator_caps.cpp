/**
 * @brief Constructs the 2D polygon vertices defining the physical shape of a pen nib.
 *
 * Each nib profile determines how the stroke responds to motion direction and pressure:
 * - Square: Simulates a rectangular felt highlighter nib (3:1 aspect ratio), oriented vertically.
 * - Chisel: Simulates a broad-edge calligraphy nib angled at -45° (top-right to bottom-left slant).
 * - Round: Simulates a circular ballpoint or stylus nib using radial discretization.
 *
 * @param capType The requested nib profile (Round, Chisel, Square).
 * @param r The nominal stroke radius (half of full stroke width) in canvas units / millimeters.
 * @return Ordered list of 2D vertices centered at (0, 0).
 */
std::vector<Point2D> GetNibVertices(CapType capType, double r) {
    std::vector<Point2D> verts;

    switch (capType) {
        case CapType::Square: {
            // Highlighter nib: narrow horizontal width (hw = 0.45r), tall vertical blade (hh = 1.3r)
            // Aspect ratio ~ 3:1 creates thick horizontal bands and thin vertical strokes.
            double hw = r * 0.45;
            double hh = r * 1.3;
            verts = {
                { -hw, -hh }, // Top-Left corner
                { +hw, -hh }, // Top-Right corner
                { +hw, +hh }, // Bottom-Right corner
                { -hw, +hh }  // Bottom-Left corner
            };
            break;
        }

        case CapType::Chisel: {
            // Calligraphy nib: fixed 45-degree angled diamond blade.
            // Produces hairline strokes when moving parallel to 45°, thick ribbons when moving at 135°.
            // We parameterize the blade using major-axis vector (dx, dy) and minor-axis normal (nx, ny).
            constexpr double angle = M_PI * -0.25; // Fixed 45-degree fountain pen slant
            double dx = std::cos(angle) * r * 1.3; // Major axis half-length
            double dy = std::sin(angle) * r * 1.3;
            double nx = -dy * 0.1;                 // Minor axis half-thickness (10% aspect ratio)
            double ny =  dx * 0.1;
            verts = {
                { -dx - nx, -dy - ny }, // Rear blade tip
                { +dx - nx, +dy - ny }, // Right blade corner
                { +dx + nx, +dy + ny }, // Front blade tip
                { -dx + nx, -dy + ny }  // Left blade corner
            };
            break;
        }

        case CapType::Round:
        default: {
            // Standard circular nib: sampled with 32 radial vertices for ultra-smooth curves
            // Parametric circle: x = r * cos(theta), y = r * sin(theta) for theta in [0, 2*pi)
            constexpr int steps = 32;
            verts.reserve(steps);
            for (int i = 0; i < steps; ++i) {
                double a = (2.0 * M_PI * i) / steps;
                verts.push_back({ std::cos(a) * r, std::sin(a) * r });
            }
            break;
        }
    }
    return verts;
}

/**
 * @brief Computes the support offsets for the left and right rails perpendicular to the stroke tangent.
 *
 * For a moving nib, the ribbon rails (left and right envelopes) are generated by tracking the
 * extremal support vertices of the nib shape in the normal direction (nx, ny):
 * - Left rail: Extremum that maximizes dot product (v . n)
 * - Right rail: Extremum that minimizes dot product (v . n)
 *
 * @param capType Nib profile.
 * @param r Stroke radius.
 * @param nx Unit normal X component (+90 degrees from stroke tangent).
 * @param ny Unit normal Y component (+90 degrees from stroke tangent).
 * @param outLeft Output offset vector from centerline to left ribbon edge.
 * @param outRight Output offset vector from centerline to right ribbon edge.
 */
void GetRibbonOffsets(CapType capType, double r, double nx, double ny,
                      Point2D& outLeft, Point2D& outRight) {
    if (capType == CapType::Round) {
        // Circle is isotropic: support points are always exactly ±r along the normal vector.
        outLeft  = {  nx * r,  ny * r };
        outRight = { -nx * r, -ny * r };
        return;
    }

    // For Square (highlighter) and Chisel (calligraphy):
    // The ribbon edges attach directly to the extreme corners of the actual nib polygon.
    auto verts = GetNibVertices(capType, r);
    Point2D bestLeft = verts[0];
    Point2D bestRight = verts[0];

    // Stroke tangent vector corresponding to normal (nx, ny):
    // Since normal is (+nx, +ny) rotated +90° from tangent (ux, uy),
    // rotating normal by -90° recovers tangent: (ux, uy) = (-ny, nx).
    double ux = -ny;
    double uy = nx;

    double maxDot = -1e9;
    double minDot = 1e9;
    double maxDotTan = 1e9;
    double minDotTan = 1e9;

    for (const auto& v : verts) {
        // Project vertex onto normal axis (measures lateral extension)
        double dot = v.x * nx + v.y * ny;
        // Project vertex onto tangent axis (measures longitudinal alignment)
        double tan = v.x * ux + v.y * uy;

        // Find vertex maximizing lateral displacement to the left
        if (dot > maxDot + 1e-5) {
            maxDot = dot;
            bestLeft = v;
            maxDotTan = tan;
        } else if (std::abs(dot - maxDot) <= 1e-5) {
            // Break tie consistently: pick the trailing corner (smallest tangent projection)
            // to avoid abrupt zig-zags when moving parallel to nib facets.
            if (tan < maxDotTan) {
                bestLeft = v;
                maxDotTan = tan;
            }
        }

        // Find vertex maximizing lateral displacement to the right (most negative dot)
        if (dot < minDot - 1e-5) {
            minDot = dot;
            bestRight = v;
            minDotTan = tan;
        } else if (std::abs(dot - minDot) <= 1e-5) {
            // Break tie consistently by picking the trailing corner (smallest tangent projection)
            if (tan < minDotTan) {
                bestRight = v;
                minDotTan = tan;
            }
        }
    }

    outLeft  = bestLeft;
    outRight = bestRight;
}

