/**
 * @brief Generates a closed nib footprint polygon for a single-point tap (pen down and up without motion).
 *
 * A single tap has no stroke length or tangent vector; it renders the full geometric cross-section
 * of the selected nib (circle for Round, oriented rectangle for Square, slanted diamond for Chisel).
 */
InkPath InkGenerator::TraceCap(const StrokePoint& pt, CapType capType) {
    InkPath path;
    auto verts = InkInternal::GetNibVertices(capType, pt.r);
    if (verts.empty()) return path;

    path.move_to(pt.x + verts[0].x, pt.y + verts[0].y);
    for (size_t i = 1; i < verts.size(); ++i) {
        path.line_to(pt.x + verts[i].x, pt.y + verts[i].y);
    }
    path.close();
    return path;
}

/**
 * @brief Universal endcap dispatcher: connects the ribbon's left and right rails across an open terminus.
 *
 * Handles both the stroke tail (end of stroke: left rail -> right rail) and head (beginning of stroke:
 * right rail -> left rail). Dispatches to polygonal facet traversal or circular arc generation based
 * on CapType.
 *
 * @param path Destination InkPath.
 * @param center Centerline vertex at the terminus.
 * @param leftPt Left boundary point at the terminus.
 * @param rightPt Right boundary point at the terminus.
 * @param capType Nib profile style.
 * @param isTail True if capping the end of the stroke; false if capping the start.
 * @param dirX Optional hint vector X (stroke direction at terminus).
 * @param dirY Optional hint vector Y (stroke direction at terminus).
 */
void InkGenerator::TraceCap(InkPath& path,
                            const StrokePoint& center,
                            const Point2D& leftPt,
                            const Point2D& rightPt,
                            CapType capType,
                            bool isTail,
                            double dirX,
                            double dirY) {
    // When tracing the tail (end of stroke): path flows along left rail forward,
    // so cap starts at leftPt and ends at rightPt.
    // When tracing the head (start of stroke): cap closes from rightPt back to leftPt.
    const Point2D& startPt = isTail ? leftPt : rightPt;
    const Point2D& endPt   = isTail ? rightPt : leftPt;

    // Chord vector connecting startPt -> endPt
    double vx = endPt.x - startPt.x;
    double vy = endPt.y - startPt.y;
    double vLen = std::hypot(vx, vy);

    if (vLen < 1e-7 || center.r < 1e-6) {
        // Degenerate zero-distance chord: close with a line
        path.line_to(endPt.x, endPt.y);
        return;
    }

    // Normal vector perpendicular to chord (pointing outward to the right of the chord)
    // Rotating (vx, vy) by -90° yields (vy, -vx).
    double ux =  vy / vLen;
    double uy = -vx / vLen;

    // If an explicit motion direction hint (dirX, dirY) was provided,
    // align outward cap vector (ux, uy) so it points in that direction.
    if ((dirX != 0.0 || dirY != 0.0) && (ux * dirX + uy * dirY < 0.0)) {
        ux = -ux;
        uy = -uy;
    }

    // Dispatch to polygon or circular arc tracer
    if (capType == CapType::Square || capType == CapType::Chisel) {
        InkInternal::TracePolygonCap(path, center, startPt, endPt, ux, uy, capType);
    } else {
        InkInternal::TraceRoundCap(path, center, startPt, endPt, ux, uy);
    }
}

