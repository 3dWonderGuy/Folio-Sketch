/**
 * @brief Traces a smooth round cap arc connecting startPt to endPt around a centerline vertex.
 *
 * When capping a ribbon, startPt and endPt may have slightly different radii due to stroke width
 * taper or asymmetric corner miter offsets. This tracer interpolates both the sweep angle and the
 * radial distance, guaranteeing a smooth transition without self-intersecting loops or sharp steps.
 *
 * @param path Destination InkPath being constructed.
 * @param center Centerline vertex at the terminus.
 * @param startPt Point on the initiating rail edge (left if tail, right if head).
 * @param endPt Point on the terminating rail edge (right if tail, left if head).
 * @param ux X component of outward-pointing vector away from stroke interior.
 * @param uy Y component of outward-pointing vector away from stroke interior.
 */
void TraceRoundCap(InkPath& path,
                   const StrokePoint& center,
                   const Point2D& startPt,
                   const Point2D& endPt,
                   double ux, double uy) {
    // Calculate polar radii from centerline vertex to both rail endpoints
    double rStart = std::hypot(startPt.x - center.x, startPt.y - center.y);
    double rEnd   = std::hypot(endPt.x - center.x, endPt.y - center.y);
    if (rStart < 1e-6 && rEnd < 1e-6) {
        // Degenerate zero-radius cap: collapse directly to endPt
        path.line_to(endPt.x, endPt.y);
        return;
    }

    // Polar angles from center to start and end vertices in [-pi, pi]
    double aStart = std::atan2(startPt.y - center.y, startPt.x - center.x);
    double aEnd   = std::atan2(endPt.y - center.y, endPt.x - center.x);

    // Two possible arcs connect aStart and aEnd along the circle:
    // Arc 1: Counter-clockwise sweep normalized to [0, 2*pi)
    double sweep1 = aEnd - aStart;
    while (sweep1 < 0.0) sweep1 += 2.0 * M_PI;
    while (sweep1 >= 2.0 * M_PI) sweep1 -= 2.0 * M_PI;

    // Arc 2: Clockwise sweep (negative)
    double sweep2 = sweep1 - 2.0 * M_PI;

    // Check which arc midpoint points outward in the direction of (ux, uy).
    // An endcap MUST bulge outward from the stroke, never invert backward into the ribbon interior!
    double mid1 = aStart + sweep1 * 0.5;
    double dot1 = std::cos(mid1) * ux + std::sin(mid1) * uy;

    double sweep = (dot1 >= 0.0) ? sweep1 : sweep2;
    double absSweep = std::abs(sweep);

    // If arc is negligible, a straight segment connects the rails
    if (absSweep < 1e-4) {
        path.line_to(endPt.x, endPt.y);
        return;
    }

    // Adaptive tessellation: allocate 2 to 16 steps proportional to sweep angle
    // A full semicircle (pi radians) receives 12 segments for a smooth curved cap.
    const int arcSteps = std::clamp(static_cast<int>(std::ceil(12.0 * (absSweep / M_PI))), 2, 16);
    for (int i = 1; i < arcSteps; ++i) {
        double t = static_cast<double>(i) / arcSteps;
        // Interpolate polar angle
        double a = aStart + t * sweep;
        // Interpolate radius linearly to smoothly handle asymmetric rail widths
        double r = rStart + t * (rEnd - rStart);
        path.line_to(center.x + std::cos(a) * r, center.y + std::sin(a) * r);
    }

    path.line_to(endPt.x, endPt.y);
}

/**
 * @brief Traces a polygonal endcap (Square/Chisel) connecting startPt to endPt around a centerline vertex.
 *
 * For non-circular nibs, the endcap follows the facet boundaries of the nib polygon.
 * This method finds the nearest nib vertices to startPt and endPt, evaluates both CCW and CW
 * paths along the perimeter, and chooses the path whose average vertex projection points outward (ux, uy).
 *
 * @param path Destination InkPath.
 * @param center Centerline vertex at the terminus.
 * @param startPt Initiating rail point.
 * @param endPt Terminating rail point.
 * @param ux X component of outward direction.
 * @param uy Y component of outward direction.
 * @param capType Nib profile (Square or Chisel).
 */
void TracePolygonCap(InkPath& path,
                     const StrokePoint& center,
                     const Point2D& startPt,
                     const Point2D& endPt,
                     double ux, double uy,
                     CapType capType) {
    auto verts = GetNibVertices(capType, center.r);
    if (verts.empty()) {
        path.line_to(endPt.x, endPt.y);
        return;
    }

    // Transform rail endpoints into local coordinates relative to the centerline vertex
    Point2D startRel = { startPt.x - center.x, startPt.y - center.y };
    Point2D endRel   = { endPt.x - center.x,   endPt.y - center.y };

    // Find the closest polygon vertex indices to startRel and endRel
    int startIdx = 0, endIdx = 0;
    double minDStart = 1e9, minDEnd = 1e9;
    for (int i = 0; i < static_cast<int>(verts.size()); ++i) {
        double ds = std::hypot(verts[i].x - startRel.x, verts[i].y - startRel.y);
        double de = std::hypot(verts[i].x - endRel.x,   verts[i].y - endRel.y);
        if (ds < minDStart) { minDStart = ds; startIdx = i; }
        if (de < minDEnd)   { minDEnd = de;   endIdx = i; }
    }

    // If both rails share the same closest vertex, cap is a direct line
    if (startIdx == endIdx) {
        path.line_to(endPt.x, endPt.y);
        return;
    }

    const int K = static_cast<int>(verts.size());

    // Generate Candidate 1: Counter-Clockwise traversal around the polygon perimeter
    std::vector<int> pathCCW;
    for (int idx = (startIdx + 1) % K; idx != endIdx; idx = (idx + 1) % K) {
        pathCCW.push_back(idx);
    }

    // Generate Candidate 2: Clockwise traversal around the polygon perimeter
    std::vector<int> pathCW;
    for (int idx = (startIdx - 1 + K) % K; idx != endIdx; idx = (idx - 1 + K) % K) {
        pathCW.push_back(idx);
    }

    // Evaluator: Computes the mean projection of path vertices onto outward vector (ux, uy).
    // The candidate that points outward away from the ribbon has a positive average projection.
    auto evalProj = [&](const std::vector<int>& p) -> double {
        if (p.empty()) return -1e9;
        double sum = 0.0;
        for (int idx : p) {
            sum += (verts[idx].x - startRel.x) * ux + (verts[idx].y - startRel.y) * uy;
        }
        return sum / static_cast<double>(p.size());
    };

    double projCCW = evalProj(pathCCW);
    double projCW  = evalProj(pathCW);

    // Select the traversal direction facing outward
    const auto& chosenPath = (projCCW >= projCW) ? pathCCW : pathCW;
    for (int idx : chosenPath) {
        path.line_to(center.x + verts[idx].x, center.y + verts[idx].y);
    }
    path.line_to(endPt.x, endPt.y);
}

